import { createHash, createHmac } from "node:crypto";

function hash(value: string | Uint8Array): string {
  return createHash("sha256").update(value).digest("hex");
}
function hmac(key: string | Uint8Array, value: string): Buffer {
  return createHmac("sha256", key).update(value, "utf8").digest();
}

// AWS SigV4 single-chunk signing. Only server-configured endpoints are signed.
// No SDK dependency is introduced; the signer is checked against AWS's vector.
export function signS3Request(input: {
  method: "GET" | "PUT";
  url: URL;
  region: string;
  accessKeyId: string;
  secretAccessKey: string;
  sessionToken?: string;
  body?: Uint8Array;
  contentType?: string;
  range?: string;
  now?: Date;
}): Headers {
  const timestamp = (input.now ?? new Date())
    .toISOString()
    .replace(/[-:]|\.\d{3}/g, "");
  const day = timestamp.slice(0, 8);
  const payloadHash = hash(input.body ?? new Uint8Array());
  const headers = new Headers({
    host: input.url.host,
    "x-amz-date": timestamp,
    "x-amz-content-sha256": payloadHash,
  });
  if (input.contentType) headers.set("content-type", input.contentType);
  if (input.range) headers.set("range", input.range);
  if (input.sessionToken)
    headers.set("x-amz-security-token", input.sessionToken);
  const sorted = [...headers.entries()].sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  );
  const names = sorted.map(([name]) => name).join(";");
  const canonicalHeaders = sorted
    .map(([name, value]) => `${name}:${value.trim().replace(/\s+/g, " ")}\n`)
    .join("");
  // Object keys are generated by the server from validated IDs and a UUID;
  // endpoints cannot contain query strings. Keep S3 path slashes unchanged.
  const canonical = [
    input.method,
    input.url.pathname,
    "",
    canonicalHeaders,
    names,
    payloadHash,
  ].join("\n");
  const scope = `${day}/${input.region}/s3/aws4_request`;
  const signingKey = hmac(
    hmac(hmac(hmac(`AWS4${input.secretAccessKey}`, day), input.region), "s3"),
    "aws4_request",
  );
  const signature = hmac(
    signingKey,
    ["AWS4-HMAC-SHA256", timestamp, scope, hash(canonical)].join("\n"),
  ).toString("hex");
  headers.set(
    "authorization",
    `AWS4-HMAC-SHA256 Credential=${input.accessKeyId}/${scope}, SignedHeaders=${names}, Signature=${signature}`,
  );
  return headers;
}
